$map = $mapCsv -split "`r?`n" | Where-Object { $_.Trim() -ne "" } | ForEach-Object {
    $p = $_.Split(",")
    [pscustomobject]@{ source_id = [int]$p[0]; target_id = [int]$p[1] }
}

$total = 0
$downloaded = 0
$skipped = 0

Write-Host "NRO Yanii - Costume batch 01"
Write-Host "Server root: $serverRoot"
Write-Host "Image range: 32212-32486"

foreach ($zoom in 1..4) {
    $targetDir = Join-Path $serverRoot ("resources\normal\image\{0}\icon" -f $zoom)
    New-Item -ItemType Directory -Force -Path $targetDir | Out-Null

    foreach ($m in $map) {
        $total++
        $src = [int]$m.source_id
        $dst = [int]$m.target_id
        $target = Join-Path $targetDir ("{0}.png" -f $dst)

        if ((Test-Path $target) -and -not $Force) {
            $skipped++
            continue
        }

        $url = "{0}/x{1}/{2}.png" -f $baseUrl, $zoom, $src
        try {
            Invoke-WebRequest -Uri $url -OutFile $target -UseBasicParsing
            if ((Get-Item $target).Length -le 8) {
                throw "File qua nho"
            }
            $downloaded++
        } catch {
            if (Test-Path $target) { Remove-Item $target -Force }
            throw "Tai asset that bai: $url -> $target`n$($_.Exception.Message)"
        }
    }
}

Write-Host ""
Write-Host ("Hoan tat. downloaded={0}, skipped={1}, total={2}" -f $downloaded,$skipped,$total)
Write-Host "Tiep theo import database/migrations/add_costumes_batch_01.sql va build/restart server."
